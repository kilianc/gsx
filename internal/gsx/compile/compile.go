const (
	SoftHeader        = "// Code generated by gsxgo. Edits may be overwritten on regen.\n"
	StaticcheckHeader = "//lint:file-ignore ST1001 dot imports are required in generated code\n"
)

const maxSingleLineCallLen = 80

type compileResult struct {
	fset        *gotoken.FileSet
	af          *goast.File
	mapping     []placeholder
	rewritten   []byte
	qualifyHTML bool
}

func compilePipeline(path string, src []byte) (*compileResult, error) {
	rewritten, mapping, err := rewriteTagsToPlaceholders(src)
	if err != nil {
		return nil, err
	}
	rewritten = normalizeParenWrappedPlaceholder(rewritten)

	fset := gotoken.NewFileSet()
	af, err := parser.ParseFile(fset, path+".go", rewritten, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("%w\n\n-- rewritten preview --\n%s", err, previewLines(string(rewritten), 80))
	}

	funcReturnTypes := resolveImportedFuncTypes(af)
	if funcReturnTypes == nil {
		funcReturnTypes = map[string]string{}
	}
	for name, typ := range collectLocalFuncReturnTypes(af) {
		funcReturnTypes[name] = typ
	}

	funcParams := resolveImportedFuncParams(af)
	if funcParams == nil {
		funcParams = map[string][]gomponents.FuncParam{}
	}
	for name, params := range collectLocalFuncParams(af) {
		funcParams[name] = params
	}

	qualifyHTML := hasUserDotImports(af)
	htmlPrefix := ""
	if qualifyHTML {
		htmlPrefix = "html"
	}

	ctx := gomponents.Context{
		VarTypes:        inferVarTypesFromPlaceholders(af, mapping, funcReturnTypes),
		FuncReturnTypes: funcReturnTypes,
		FuncParams:      funcParams,
		HTMLPrefix:      htmlPrefix,
	}

	for i := range mapping {
		ex, err := gomponents.LowerNodes([]ast.Node{mapping[i].node}, ctx)
		if err != nil {
			return nil, err
		}
		clearTokenPos(ex)
		mapping[i].expr = ex
	}

	return &compileResult{fset: fset, af: af, mapping: mapping, rewritten: rewritten, qualifyHTML: qualifyHTML}, nil
}

// CompileFile compiles a Go-first .gsx source (a Go file with embedded `<tag>` expressions)
// into a gofmt'd Go source file.
func CompileFile(path string, src []byte) ([]byte, error) {
	cr, err := compilePipeline(path, src)
	if err != nil {
		return nil, err
	}

	ensureImports(cr.af, cr.mapping, cr.qualifyHTML)

	var buf bytes.Buffer
	if err := format.Node(&buf, cr.fset, cr.af); err != nil {
		return nil, err
	}

	gofmted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, err
	}

	pretty, err := substitutePlaceholdersWithPrettyExprs(string(gofmted), cr.mapping, maxSingleLineCallLen)
	if err != nil {
		return nil, err
	}

	out := append([]byte(nil), []byte(SoftHeader)...)
	out = append(out, []byte(strings.TrimRight(StaticcheckHeader, "\n"))...)
	out = append(out, '\n', '\n')
	out = append(out, []byte(formatImportGroups(pretty))...)
	final, err := format.Source(out)
	if err != nil {
		return nil, fmt.Errorf("gofmt final: %w\n\n-- output preview --\n%s", err, previewLines(string(out), 120))
	}
	return final, nil
}

// CompileFileForLSP compiles a .gsx source into a Go source file suitable for feeding to gopls.
//
// Unlike CompileFile, it does NOT inline tag expressions at call sites. Instead, tag expressions are
// replaced with stable placeholder calls like `__gsx_expr_1()` and the corresponding helper functions
// are appended to the file.
//
// It also returns the rewritten Go-ish source (tags -> placeholders) to help higher layers build
// best-effort mappings back to the original .gsx file.
func CompileFileForLSP(path string, src []byte) (goSrc []byte, sm *SourceMap, err error) {
	cr, err := compilePipeline(path, src)
	if err != nil {
		return nil, nil, err
	}

	rewritten := string(cr.rewritten)
	mapping := cr.mapping

	// normalizeParenWrappedPlaceholder may remove lines and change the positions of placeholder calls.
	// Re-index placeholder target positions so we can safely apply inline expansions.
	if mapping, err = reindexPlaceholderTargets(rewritten, mapping); err != nil {
		return nil, nil, err
	}

	loweredExprs := map[string]string{}
	for i := range mapping {
		loweredExprs[mapping[i].name] = formatExpr(mapping[i].expr)
	}

	// Apply minimal import edits and inline placeholder expansions to produce a gopls-friendly Go view.
	req := detectRequiredImports(mapping, mapsToSlice(loweredExprs))
	req.qualifyHTML = cr.qualifyHTML
	impRes := applyImportEdits(rewritten, req)

	// When we changed imports, all subsequent placeholder offsets shift.
	afterImports := impRes.out
	adjusted := make([]placeholder, len(mapping))
	for i := range mapping {
		p := mapping[i]
		ns, _ := impRes.mp.tgtOffsetFromSrcOffset(p.tgtStart)
		ne, _ := impRes.mp.tgtOffsetFromSrcOffset(p.tgtEnd)
		p.tgtStart = ns
		p.tgtEnd = ne
		adjusted[i] = p
	}

	expRes := applyInlineExpansions(afterImports, adjusted, loweredExprs, true, true)
	goView := expRes.out

	// Build source map: src(.gsx) -> rewritten(placeholders) -> afterImports -> goView.
	srcStr := string(src)
	srcToRew, rewToSrc := buildRewriteMappers(srcStr, mapping)

	sm = &SourceMap{
		src:                     newLineIndex(srcStr),
		tgt:                     newLineIndex(goView),
		srcToRewritten:          srcToRew,
		rewrittenToSrc:          rewToSrc,
		rewrittenToAfterImports: impRes.mp,
		afterImportsToRewritten: impRes.mp,
		afterImportsToTgt:       expRes.mp,
		tgtToAfterImports:       expRes.mp,
	}

	return []byte(goView), sm, nil
}

func reindexPlaceholderTargets(rewritten string, phs []placeholder) ([]placeholder, error) {
	// Each placeholder name is unique, so we can locate `name()` exactly once.
	// We scan left-to-right to keep it linear and robust.
	out := make([]placeholder, len(phs))
	searchFrom := 0
	for i := range phs {
		needle := phs[i].name + "()"
		j := strings.Index(rewritten[searchFrom:], needle)
		if j < 0 {
			return nil, fmt.Errorf("lsp: could not locate placeholder %q in rewritten source", needle)
		}
		j += searchFrom
		p := phs[i]
		p.tgtStart = j
		p.tgtEnd = j + len(needle)
		out[i] = p
		searchFrom = p.tgtEnd
	}
	return out, nil
}

func mapsToSlice(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for _, v := range m {
		out = append(out, v)
	}
	return out
}

func resolveImportedFuncTypes(f *goast.File) map[string]string {
	modPath, modRoot := module.FindModuleInfo()
	if modPath == "" {
		return nil
	}
	result := map[string]string{}
	for _, spec := range f.Imports {
		importPath := strings.Trim(spec.Path.Value, `"`)
		if !strings.HasPrefix(importPath, modPath+"/") && importPath != modPath {
			continue
		}
		relDir := strings.TrimPrefix(importPath, modPath)
		relDir = strings.TrimPrefix(relDir, "/")
		absDir := filepath.Join(modRoot, relDir)

		isDotImport := spec.Name != nil && spec.Name.Name == "."
		localName := filepath.Base(importPath)
		if spec.Name != nil && spec.Name.Name != "." && spec.Name.Name != "_" {
			localName = spec.Name.Name
		}

		funcTypes := parseFuncReturnTypesFromDir(absDir)
		for funcName, retType := range funcTypes {
			if isDotImport {
				result[funcName] = retType
			} else {
				result[localName+"."+funcName] = retType
			}
		}
	}
	return result
}


func parseFuncReturnTypesFromDir(dir string) map[string]string {
	fset := gotoken.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, nil, 0)
	if err != nil {
		return nil
	}
	result := map[string]string{}
	for _, pkg := range pkgs {
		if strings.HasSuffix(pkg.Name, "_test") {
			continue
		}
		for _, file := range pkg.Files {
			for _, decl := range file.Decls {
				fd, ok := decl.(*goast.FuncDecl)
				if !ok || fd.Recv != nil {
					continue
				}
				if !fd.Name.IsExported() {
					continue
				}
				if fd.Type.Results == nil || fd.Type.Results.NumFields() != 1 {
					continue
				}
				retType := classifyASTReturnType(fd.Type.Results.List[0].Type, file.Imports)
				if retType != "" {
					result[fd.Name.Name] = retType
				}
			}
		}
	}
	return result
}

func classifyASTReturnType(expr goast.Expr, imports []*goast.ImportSpec) string {
	switch t := expr.(type) {
	case *goast.Ident:
		if t.Name == "string" {
			return "string"
		}
		if t.Name == "Node" {
			return "Node"
		}
	case *goast.SelectorExpr:
		if t.Sel.Name == "Node" {
			if xID, ok := t.X.(*goast.Ident); ok {
				for _, imp := range imports {
					impPath := strings.Trim(imp.Path.Value, `"`)
					localName := filepath.Base(impPath)
					if imp.Name != nil {
						localName = imp.Name.Name
					}
					if localName == xID.Name && strings.Contains(impPath, "gomponents") {
						return "Node"
					}
				}
			}
		}
	}
	return ""
}

func collectLocalFuncReturnTypes(f *goast.File) map[string]string {
	result := map[string]string{}
	for _, decl := range f.Decls {
		fd, ok := decl.(*goast.FuncDecl)
		if !ok || fd.Recv != nil {
			continue
		}
		if fd.Type.Results == nil || fd.Type.Results.NumFields() != 1 {
			continue
		}
		retType := classifyASTReturnType(fd.Type.Results.List[0].Type, f.Imports)
		if retType != "" {
			result[fd.Name.Name] = retType
		}
	}
	return result
}

